/** LM Studio Generator: every answer, tool-free, comes from authenticated ClawFedora. */
import { lstatSync, readFileSync } from "node:fs";
import { isAbsolute, join, normalize } from "node:path";
import { configSchematics } from "./config.js";
import { bridgePayload, bridgeResponse } from "./contract.mjs";

const PORT = 18891;
const BASE = "http://127.0.0.1:" + PORT;
const ROOT = process.env.OPENCLAW_LOCAL_FEDORA_ROOT || "/data/IA/Openclaw";

function localToken() {
  const root = normalize(ROOT);
  if (!isAbsolute(root) || root.split("/").includes("..")) {
    throw new Error("Racine ClawFedora invalide.");
  }
  const parent = join(root, "state", "webui");
  const file = join(parent, "bridge.token");
  try {
    // A plugin may only use the token generated by the existing local
    // ClawFedora bootstrap. Never invent, print or persist a copy.
    for (const part of [root, join(root, "state"), parent, file]) {
      if (lstatSync(part).isSymbolicLink()) {
        throw new Error("Chemin de jeton ClawFedora lié : accès refusé.");
      }
    }
    const info = lstatSync(file);
    if (!info.isFile() || (info.mode & 0o077) !== 0) {
      throw new Error("Le jeton du pont doit être un fichier privé 0600.");
    }
    if (typeof process.getuid === "function" && info.uid !== process.getuid()) {
      throw new Error("Le jeton du pont n'appartient pas à la session courante.");
    }
    const value = readFileSync(file, "utf8").trim();
    if (!/^[a-f0-9]{64}$/.test(value)) {
      throw new Error("Jeton du pont ClawFedora invalide.");
    }
    return value;
  } catch (error) {
    if (error instanceof Error && !("code" in error)) throw error;
    throw new Error(
      "Pont ClawFedora absent : installer le socle, démarrer "
      + "clawfedora-webui-bridge.service et vérifier son jeton local 0600.",
    );
  }
}

async function localJson(url, token, init) {
  const headers = {
    Authorization: "Bearer " + token,
    Accept: "application/json",
    ...(init?.body ? { "Content-Type": "application/json" } : {}),
  };
  const response = await fetch(url, { ...init, headers });
  const body = await response.json().catch(() => null);
  if (!response.ok) {
    // Server messages are bounded and generated locally. No token or prompt logs.
    throw new Error(
      "Pont ClawFedora : "
      + String(body?.error?.message ?? "requête refusée").slice(0, 300),
    );
  }
  return body;
}

export async function generate(ctl, history) {
  const selected = ctl.getPluginConfig(configSchematics);
  const projectId = selected.get("projectId");
  const agentRole = selected.get("agentRole");
  // Validate BEFORE any call; never silently truncate prior project markers.
  const messages = history.getMessagesArray();
  const payload = bridgePayload(messages, projectId, agentRole);
  const token = localToken();
  const signal = ctl.abortSignal;

  if (projectId) {
    const details = await localJson(
      BASE + "/v1/atelier?project=" + encodeURIComponent(projectId),
      token,
      { method: "GET", signal },
    );
    if (details?.selected?.id !== projectId) {
      throw new Error("Le projet sélectionné n'existe pas dans cet atelier.");
    }
  }

  const answer = await localJson(
    BASE + "/v1/chat/completions",
    token,
    { method: "POST", body: JSON.stringify(payload), signal },
  );
  signal.throwIfAborted();
  const result = bridgeResponse(200, answer);
  // Keep the bridge's real provenance and marker in the LM Studio chat history,
  // so a user cannot accidentally rebind an older conversation to another project.
  ctl.fragmentGenerated(result);
}
