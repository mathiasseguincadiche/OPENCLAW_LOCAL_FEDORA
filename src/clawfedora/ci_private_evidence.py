"""Explicit operator-only CI provenance for GitHub/GitLab private repositories.

This standalone command is never registered as an OpenClaw agent tool.
Credentials stay in a private local file and never appear in returned reports.
No workflows, artifacts or logs are downloaded and no writes are attempted.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import stat
import urllib.error
import urllib.request
from pathlib import Path
from typing import Any
from urllib.parse import urlsplit

from clawfedora.ci_evidence import (
    MAX_BODY,
    ProofRefused,
    _NoRedirect,
    verify_public_run,
    verify_public_run_with_jobs,
)

GITHUB_API = "https://api.github.com"
GITLAB_API = "https://gitlab.com"
GITHUB_PATH = re.compile(r"/repos/[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+/actions/runs/[0-9]+")
GITLAB_PATH = re.compile(
    r"/api/v4/projects/[A-Za-z0-9_.%-]+/pipelines/[0-9]+"
)


def read_operator_token(path: Path) -> str:
    """Private 0600 regular file owned by this user, no symlinks or overrides."""
    try:
        fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_CLOEXEC)
    except OSError as exc:
        raise ProofRefused("Fichier du jeton privé inaccessible ou lié") from exc
    with os.fdopen(fd, "rb") as reader:
        meta = os.fstat(reader.fileno())
        if (
            not stat.S_ISREG(meta.st_mode)
            or meta.st_uid != os.geteuid()
            or meta.st_mode & 0o077
            or meta.st_size > 4096
        ):
            raise ProofRefused("Jeton requis dans un fichier régulier privé 0600")
        raw = reader.read(4097)
    if len(raw) > 4096:
        raise ProofRefused("Jeton trop long")
    try:
        token = raw.decode("ascii").strip()
    except UnicodeDecodeError as exc:
        raise ProofRefused("Jeton invalide") from exc
    if not 16 <= len(token) <= 4096 or any(c.isspace() for c in token):
        raise ProofRefused("Jeton opérateur absent ou malformé")
    return token


def _permitted(provider: str, url: str) -> bool:
    """Only exact official read-only endpoint shapes generated by ci_evidence."""
    parsed = urlsplit(url)
    if (parsed.scheme != "https" or parsed.username or parsed.password
            or parsed.port is not None or parsed.fragment):
        return False
    if provider == "github":
        if parsed.netloc != "api.github.com":
            return False
        return (
            bool(GITHUB_PATH.fullmatch(parsed.path)) and not parsed.query
            or parsed.path.endswith("/jobs")
            and bool(GITHUB_PATH.fullmatch(parsed.path.removesuffix("/jobs")))
            and parsed.query == "per_page=100"
        )
    if provider == "gitlab":
        if parsed.netloc != "gitlab.com":
            return False
        return (
            bool(GITLAB_PATH.fullmatch(parsed.path)) and not parsed.query
            or parsed.path.endswith("/jobs")
            and bool(GITLAB_PATH.fullmatch(parsed.path.removesuffix("/jobs")))
            and parsed.query == "per_page=100"
        )
    return False


def _authenticated_reader(provider: str, token: str):
    """A closure with no externally chosen host; reject redirects and errors."""
    def read(url: str) -> Any:
        if not _permitted(provider, url):
            raise ProofRefused("URL ou opération CI privée interdite")
        headers = {
            "Accept": "application/vnd.github+json, application/json",
            "User-Agent": "clawfedora-private-ci-proof/1",
        }
        if provider == "github":
            headers["Authorization"] = "Bearer " + token
        else:
            headers["PRIVATE-TOKEN"] = token
        request = urllib.request.Request(url, headers=headers, method="GET")
        opener = urllib.request.build_opener(_NoRedirect(), urllib.request.ProxyHandler({}))
        try:
            with opener.open(request, timeout=12) as response:
                if response.status != 200:
                    raise ProofRefused("API CI privée indisponible")
                raw = response.read(MAX_BODY + 1)
        except (OSError, urllib.error.URLError) as exc:
            raise ProofRefused("Impossible de lire l'API privée officielle") from exc
        if len(raw) > MAX_BODY:
            raise ProofRefused("Réponse CI privée trop volumineuse")
        try:
            return json.loads(raw)
        except (UnicodeDecodeError, json.JSONDecodeError) as exc:
            raise ProofRefused("Réponse CI privée malformée") from exc
    return read


def verify_private_run(
    provider: str, repository: str, run_id: int, commit: str,
    *, token_file: Path, jobs: bool = False,
) -> dict[str, Any]:
    """Operator-attested, read-only pipeline status scoped to the exact SHA."""
    # Reject malformed selectors before reading any private credential.
    from clawfedora.ci_evidence import SHA, _repo_parts

    _repo_parts(provider, repository)
    if type(run_id) is not int or run_id <= 0 or not SHA.fullmatch(commit):
        raise ProofRefused("Identifiant de run et SHA complets requis")
    token = read_operator_token(token_file)
    proof = verify_public_run_with_jobs if jobs else verify_public_run
    report = proof(provider, repository, run_id, commit,
                   getter=_authenticated_reader(provider, token))
    report["provenance"] = "OFFICIAL_PRIVATE_FORGE_API_OPERATOR_AUTH"
    report["authentication"] = "private_local_token_file_not_exported"
    if jobs:
        report["jobs_scope"] = "private_job_metadata_only"
    return report


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Preuve CI privée, consultation humaine uniquement"
    )
    parser.add_argument("--provider", required=True, choices=("github", "gitlab"))
    parser.add_argument("--repo", required=True)
    parser.add_argument("--run-id", required=True, type=int)
    parser.add_argument("--commit", required=True)
    parser.add_argument("--token-file", required=True, type=Path)
    parser.add_argument("--jobs", action="store_true")
    args = parser.parse_args(argv)
    try:
        result = verify_private_run(
            args.provider, args.repo, args.run_id, args.commit,
            token_file=args.token_file, jobs=args.jobs,
        )
        print(json.dumps(result, ensure_ascii=False, indent=2))
        return 0 if result["verdict"] == "VERIFIED_RUN_SUCCESS" else 1
    except ProofRefused as exc:
        print(json.dumps({"verdict": "REFUSED", "reason": str(exc)}, ensure_ascii=False))
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
